import argparse
import csv
from pathlib import Path
from tempfile import NamedTemporaryFile

import torch
from tqdm.auto import tqdm

from dataset import HPAImageDataset, NUM_CLASSES, make_loader, read_test_records
from engine import resolve_device, set_seed
from model import DEFAULT_MODEL_NAME, available_models, build_model


PUBLIC_MODEL_NAME = "bestfitting_densenet121"


def parse_args():
    parser = argparse.ArgumentParser(
        description="Inference for Human Protein Atlas baseline"
    )

    parser.add_argument("--data-dir", type=str, default="dataset")
    parser.add_argument(
        "--model",
        dest="model_name",
        type=str,
        choices=("auto",) + available_models(),
        default="auto",
        help="Use the model stored in the checkpoint, or force a model name.",
    )
    parser.add_argument(
        "--checkpoint",
        type=str,
    )
    parser.add_argument(
        "--public-pretrained", action="store_true",
        help="Run the converted Bestfitting HPA weights directly, without retraining.",
    )
    output = parser.add_mutually_exclusive_group()
    output.add_argument(
        "--submission-path",
        type=str,
    )
    output.add_argument(
        "--submission-dir", type=Path,
        help="Destination for the submission files generated by --thresholds.",
    )
    parser.add_argument(
        "--image-size", type=int, default=None,
        help="Defaults to checkpoint training configuration; legacy fallback: 256.",
    )
    parser.add_argument("--batch-size", type=int, default=16)
    parser.add_argument("--num-workers", type=int, default=0)
    thresholds = parser.add_mutually_exclusive_group()
    thresholds.add_argument(
        "--threshold", type=float, default=None,
        help="Defaults to checkpoint training configuration; legacy fallback: 0.5.",
    )
    thresholds.add_argument(
        "--thresholds", type=float, nargs="+",
        help="Generate one submission per global threshold in a single inference pass.",
    )
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--device", type=str, default="auto")

    args = parser.parse_args()
    if args.public_pretrained and args.model_name not in ("auto", PUBLIC_MODEL_NAME):
        parser.error(f"--public-pretrained requires --model auto or --model {PUBLIC_MODEL_NAME}.")
    if (args.thresholds is None) != (args.submission_dir is None):
        parser.error("--thresholds and --submission-dir must be used together.")
    if args.thresholds is not None:
        if any(not 0.0 <= threshold <= 1.0 for threshold in args.thresholds):
            parser.error("--thresholds values must be in [0, 1].")
        if len(set(args.thresholds)) != len(args.thresholds):
            parser.error("--thresholds values must be distinct.")
    return args


@torch.no_grad()
def predict_test_thresholds(model, test_loader, device, thresholds):
    model.eval()
    predictions_by_threshold = {threshold: {} for threshold in thresholds}

    progress_bar = tqdm(
        test_loader,
        desc="Kaggle test inference",
        total=len(test_loader),
        unit="batch",
        dynamic_ncols=True,
    )
    for batch in progress_bar:
        images = batch["image"].to(device, non_blocking=True)
        logits = model(images)
        probabilities = torch.sigmoid(logits).cpu()
        fallback_labels = probabilities.argmax(dim=1).tolist()

        for image_id, probability, fallback in zip(batch["id"], probabilities, fallback_labels):
            for threshold, predictions in predictions_by_threshold.items():
                labels = torch.where(probability >= threshold)[0].tolist()
                predictions[image_id] = " ".join(str(label) for label in labels or [fallback])

    return predictions_by_threshold


def predict_test(model, test_loader, device, threshold):
    return predict_test_thresholds(model, test_loader, device, (threshold,))[threshold]


def write_submission(sample_submission_path, submission_path, predictions):
    temporary_path = None
    try:
        with sample_submission_path.open(
            "r", newline="", encoding="utf-8-sig"
        ) as source_file, NamedTemporaryFile(
            "w", newline="", encoding="utf-8", delete=False,
            dir=submission_path.parent, prefix=f".{submission_path.name}.", suffix=".tmp",
        ) as output_file:
            temporary_path = Path(output_file.name)
            reader = csv.DictReader(source_file)
            writer = csv.DictWriter(output_file, fieldnames=["Id", "Predicted"])
            writer.writeheader()

            for row in reader:
                image_id = row["Id"]
                if image_id not in predictions:
                    raise KeyError(f"No prediction was produced for {image_id}")
                writer.writerow({"Id": image_id, "Predicted": predictions[image_id]})
        temporary_path.replace(submission_path)
    finally:
        if temporary_path is not None:
            temporary_path.unlink(missing_ok=True)


def run_inference(
    model,
    test_loader,
    device,
    threshold,
    sample_submission_path,
    submission_path,
):
    predictions = predict_test(model, test_loader, device, threshold)
    write_submission(sample_submission_path, submission_path, predictions)
    print(f"Submission saved to: {submission_path}")


def main():
    args = parse_args()
    set_seed(args.seed)

    data_dir = Path(args.data_dir)
    sample_submission_path = data_dir / "sample_submission.csv"
    test_image_dir = data_dir / "test"
    if args.public_pretrained:
        default_checkpoint = "load_checkpoint/bestfitting-densenet121.pth"
        default_submission = f"outputs/{PUBLIC_MODEL_NAME}/public_submission.csv"
    else:
        default_checkpoint = "outputs/baseline/best_model.pth"
        default_submission = "outputs/baseline/submission.csv"
    checkpoint_path = Path(args.checkpoint or default_checkpoint)
    submission_path = Path(args.submission_path or default_submission)

    for path in (sample_submission_path, test_image_dir, checkpoint_path):
        if not path.exists():
            raise FileNotFoundError(f"Required path not found: {path}")

    checkpoint = torch.load(
        checkpoint_path, map_location="cpu", weights_only=True
    )
    if args.public_pretrained:
        checkpoint_model_name = PUBLIC_MODEL_NAME
        model_state = checkpoint
        training_config = {"image_size": 512}
    else:
        checkpoint_model_name = checkpoint.get("model_name", DEFAULT_MODEL_NAME)
        model_state = checkpoint["model_state_dict"]
        training_config = checkpoint.get("run_config", {})
    if args.image_size is None:
        args.image_size = training_config.get("image_size", 256)
    if args.thresholds is None:
        if args.threshold is None:
            args.threshold = training_config.get("threshold", 0.5)
        print(f"Inference image size: {args.image_size}, threshold: {args.threshold}")
        submission_path.parent.mkdir(parents=True, exist_ok=True)
    else:
        print(f"Inference image size: {args.image_size}, thresholds: {args.thresholds}")
        args.submission_dir.mkdir(parents=True, exist_ok=True)
    device = resolve_device(args.device)
    pin_memory = device.type == "cuda"
    print(f"Device: {device}")

    test_records = read_test_records(sample_submission_path)
    test_dataset = HPAImageDataset(
        test_records,
        test_image_dir,
        args.image_size,
        augment=False,
    )
    test_loader = make_loader(
        test_dataset,
        indices=None,
        batch_size=args.batch_size,
        shuffle=False,
        num_workers=args.num_workers,
        seed=args.seed,
        pin_memory=pin_memory,
    )

    if args.model_name == "auto":
        model_name = checkpoint_model_name
    else:
        model_name = args.model_name
        if model_name != checkpoint_model_name:
            raise ValueError(
                f"Requested model '{model_name}', but checkpoint uses "
                f"'{checkpoint_model_name}'."
            )

    print(f"Selected model: {model_name}")
    model = build_model(
        model_name=model_name,
        num_classes=NUM_CLASSES,
        pretrained_weights="",
    ).to(device)
    model.load_state_dict(model_state)
    if args.public_pretrained:
        print(f"Loaded Bestfitting HPA weights from: {checkpoint_path}")
    else:
        print(f"Loaded checkpoint from epoch {checkpoint['epoch']}")
        if "holdout_macro_f1" in checkpoint:
            print(f"Held-out Macro-F1: {checkpoint['holdout_macro_f1']:.4f}")
        elif "best_f1" in checkpoint:
            print(f"Best validation Macro-F1: {checkpoint['best_f1']:.4f}")

    if args.thresholds is None:
        run_inference(
            model,
            test_loader,
            device,
            args.threshold,
            sample_submission_path,
            submission_path,
        )
        return

    predictions_by_threshold = predict_test_thresholds(model, test_loader, device, args.thresholds)
    for threshold, predictions in predictions_by_threshold.items():
        suffix = f"{threshold:.2f}" if threshold == round(threshold, 2) else str(threshold)
        submission_path = args.submission_dir / f"submission_t{suffix}.csv"
        write_submission(sample_submission_path, submission_path, predictions)
        print(f"Submission saved to: {submission_path}")


if __name__ == "__main__":
    main()
